const noMessages = [
    "No",
    "Are you positive? 🤔",
    "Pookie please... 🥺",
    "If you say no, I will be really sad...",
    "I will be very sad... 😢",
    "Please??? 💔",
    "Don't do this to me...",
    "Last chance! 😭",
    "You can't catch me anyway 😜"
]

const yesTeasePokes = [
    "try saying no first... I bet you want to know what happens 😏",
    "go on, hit no... just once 👀",
    "you're missing out 😈",
    "click no, I dare you 😏"
]

let yesTeasedCount = 0

let noClickCount = 0
let runawayEnabled = false
let musicPlaying = true

// Clear any previous plan so this page always requires an explicit selection
localStorage.removeItem('selectedPlan')
localStorage.removeItem('selectedCaption')

const catGif = document.getElementById('cat-gif')
const yesBtn = document.getElementById('yes-btn')
const noBtn = document.getElementById('no-btn')
const music = document.getElementById('bg-music')

function updateYesButtonState() {
    const selectedPlan = localStorage.getItem('selectedPlan')
    const enabled = Boolean(selectedPlan)
    yesBtn.disabled = !enabled
    yesBtn.style.opacity = enabled ? '1' : '0.6'
    yesBtn.style.cursor = enabled ? 'pointer' : 'not-allowed'
}

// Initialize button state based on any previously chosen plan
updateYesButtonState()

// Autoplay: audio starts muted (bypasses browser policy), unmute immediately
music.muted = true
music.volume = 0.3
music.play().then(() => {
    music.muted = false
}).catch(() => {
    // Fallback: unmute on first interaction
    document.addEventListener('click', () => {
        music.muted = false
        music.play().catch(() => {})
    }, { once: true })
})

function toggleMusic() {
    if (musicPlaying) {
        music.pause()
        musicPlaying = false
        document.getElementById('music-toggle').textContent = '🔇'
    } else {
        music.muted = false
        music.play()
        musicPlaying = true
        document.getElementById('music-toggle').textContent = '🔊'
    }
}

function selectPlan(plan) {
    const captions = {
        'Chai date': 'Tumi amar cha pata, ami tomar dudh,\nEk cup cha aar ektu golpo — shondha ta hobe smooth.',
        'Long walk': 'Long walk bole berobo, kintu actually excuse tomar shathe beshi time katano.',
        'Dinner date': 'Menu te onek kichu thakbe, kintu amar favourite dish holo ‘tumi’.'
    }

    const caption = captions[plan] || ''
    localStorage.setItem('selectedPlan', plan)
    localStorage.setItem('selectedCaption', caption)

    const message = document.getElementById('plan-selection')
    message.textContent = caption

    const captionEl = document.getElementById('plan-caption')
    if (captionEl) {
        captionEl.textContent = `Perfect! ${caption} For you, Debanjali 💖`
    }

    document.querySelectorAll('.plan-btn').forEach(btn => {
        btn.classList.toggle('selected', btn.textContent === plan)
    })

    updateYesButtonState()
}

function handleYesClick() {
    if (!runawayEnabled) {
        // Tease her to try No first
        const msg = yesTeasePokes[Math.min(yesTeasedCount, yesTeasePokes.length - 1)]
        yesTeasedCount++
        showTeaseMessage(msg)
        return
    }

    const selectedPlan = localStorage.getItem('selectedPlan')
    if (!selectedPlan) {
        showTeaseMessage('Please choose a date plan before saying yes! 💌')

        const planSection = document.getElementById('date-plan')
        planSection.classList.add('needs-selection')
        planSection.scrollIntoView({ behavior: 'smooth', block: 'center' })

        setTimeout(() => {
            planSection.classList.remove('needs-selection')
        }, 2200)

        updateYesButtonState()
        return
    }

    window.location.href = 'yes.html'
}

function showTeaseMessage(msg) {
    let toast = document.getElementById('tease-toast')
    toast.textContent = msg
    toast.classList.add('show')
    clearTimeout(toast._timer)
    toast._timer = setTimeout(() => toast.classList.remove('show'), 2500)
}

function handleNoClick() {
    noClickCount++

    // Show date plan chooser after first No click
    if (noClickCount === 1) {
        document.getElementById('date-plan').classList.remove('hidden')
    }

    // Cycle through guilt-trip messages
    const msgIndex = Math.min(noClickCount, noMessages.length - 1)
    noBtn.textContent = noMessages[msgIndex]

    // Grow the Yes button bigger each time
    const currentSize = parseFloat(window.getComputedStyle(yesBtn).fontSize)
    yesBtn.style.fontSize = `${currentSize * 1.35}px`
    const padY = Math.min(18 + noClickCount * 5, 60)
    const padX = Math.min(45 + noClickCount * 10, 120)
    yesBtn.style.padding = `${padY}px ${padX}px`

    // Shrink No button to contrast
    if (noClickCount >= 2) {
        const noSize = parseFloat(window.getComputedStyle(noBtn).fontSize)
        noBtn.style.fontSize = `${Math.max(noSize * 0.85, 10)}px`
    }

    // Swap cat GIF through stages
    const gifIndex = Math.min(noClickCount, gifStages.length - 1)
    swapGif(gifStages[gifIndex])

    // Runaway starts at click 5
    if (noClickCount >= 5 && !runawayEnabled) {
        enableRunaway()
        runawayEnabled = true
    }
}

function swapGif(src) {
    catGif.style.opacity = '0'
    setTimeout(() => {
        catGif.src = src
        catGif.style.opacity = '1'
    }, 200)
}

function enableRunaway() {
    noBtn.addEventListener('mouseover', runAway)
    noBtn.addEventListener('touchstart', runAway, { passive: true })
}

function runAway() {
    const margin = 20
    const btnW = noBtn.offsetWidth
    const btnH = noBtn.offsetHeight
    const maxX = window.innerWidth - btnW - margin
    const maxY = window.innerHeight - btnH - margin

    const randomX = Math.random() * maxX + margin / 2
    const randomY = Math.random() * maxY + margin / 2

    noBtn.style.position = 'fixed'
    noBtn.style.left = `${randomX}px`
    noBtn.style.top = `${randomY}px`
    noBtn.style.zIndex = '50'
}
